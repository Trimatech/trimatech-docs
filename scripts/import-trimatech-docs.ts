/**
 * Turns the one-page plugin docs kept as data in the trimatech.dev repo into markdown pages here,
 * and writes the plugin list the home page shows.
 *
 * Run with `pnpm import-docs`. The trimatech checkout is expected beside this one.
 */
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

import { iconSnapDoc } from "../../trimatech/content/docs/icon-snap.ts";
import { npcOutfitCreatorDoc } from "../../trimatech/content/docs/npc-outfit-creator.ts";
import { perfAuditorDoc } from "../../trimatech/content/docs/perf-auditor.ts";
import { quickActionsDoc } from "../../trimatech/content/docs/quick-actions.ts";
import { superAlignerDoc } from "../../trimatech/content/docs/super-aligner.ts";
import { terrainToolsDoc } from "../../trimatech/content/docs/terrain-tools.ts";
import type { DocBlock, PluginDoc } from "../../trimatech/content/docs/types.ts";
import { voxelizerDoc } from "../../trimatech/content/docs/voxelizer.ts";
import { plugins, type PluginSlug } from "../../trimatech/data/roblox.ts";

/** What the home page needs to draw one plugin's card. */
export type PluginCard = {
	readonly slug: string;
	readonly name: string;
	readonly version: string;
	readonly summary: string;
	readonly docsPath: string;
	readonly storeUrl: string;
};

/** Plugins whose docs are a single page imported from trimatech.dev. */
const importedDocs: Partial<Record<PluginSlug, PluginDoc>> = {
	"perf-auditor": perfAuditorDoc,
	"super-aligner": superAlignerDoc,
	"terrain-tools": terrainToolsDoc,
	voxelizer: voxelizerDoc,
	"icon-snap": iconSnapDoc,
	"quick-actions": quickActionsDoc,
	"npc-outfit-creator": npcOutfitCreatorDoc,
};

/** Plugins whose docs are written as markdown in their own repo and mounted as a docs section here. */
const ownSections: Partial<Record<PluginSlug, { readonly summary: string; readonly docsPath: string }>> = {
	"city-builder": {
		summary:
			"Draw roads, rails and junctions, place buildings that resize, and generate a whole city from a map or from a seed.",
		docsPath: "/city-builder/",
	},
	"click-to-build": {
		summary: "Build shapes, paths, walls and modular structures by clicking in the viewport.",
		docsPath: "/click-to-build/intro",
	},
};

const siteDir = path.resolve(import.meta.dirname, "..");
const pluginDocsDir = path.join(siteDir, "docs/plugins");

const storeUrl = (assetId: number) => `https://create.roblox.com/store/asset/${assetId}`;

/** The pages are MDX, where a bare `{` or `<` starts an expression or a tag. */
const escapeMdx = (text: string) => text.replace(/[{<]/g, (char) => `\\${char}`);

const renderBlock = (block: DocBlock): string => {
	switch (block.kind) {
		case "paragraph":
			return escapeMdx(block.text);
		case "bullets":
			return block.items.map((item) => `- ${escapeMdx(item)}`).join("\n");
		case "steps":
			return block.items.map((item, index) => `${index + 1}. ${escapeMdx(item)}`).join("\n");
		case "note":
			return `:::note\n\n${escapeMdx(block.text)}\n\n:::`;
		case "code":
			return `\`\`\`${block.language}\n${block.code}\n\`\`\``;
		default: {
			const _exhaustive: never = block;
			return _exhaustive;
		}
	}
};

const renderPage = (args: {
	readonly slug: string;
	readonly name: string;
	readonly version: string;
	readonly assetId: number;
	readonly position: number;
	readonly doc: PluginDoc;
}): string => {
	const { slug, name, version, assetId, position, doc } = args;
	const sections = doc.sections.map(
		(section) => `## ${escapeMdx(section.heading)}\n\n${section.blocks.map(renderBlock).join("\n\n")}`,
	);
	return [
		"---",
		`title: ${JSON.stringify(name)}`,
		`description: ${JSON.stringify(doc.summary)}`,
		`sidebar_position: ${position}`,
		"---",
		"",
		"{/* Generated by scripts/import-trimatech-docs.ts. Edit the source in the trimatech repo, not this file. */}",
		"",
		`<img src="/img/plugins/${slug}.png" alt="" width="72" height="72" className="plugin-icon" />`,
		"",
		escapeMdx(doc.summary),
		"",
		`Version ${version}. [Get it on the Creator Store](${storeUrl(assetId)}).`,
		"",
		sections.join("\n\n"),
		"",
	].join("\n");
};

rmSync(pluginDocsDir, { recursive: true, force: true });
mkdirSync(pluginDocsDir, { recursive: true });

const cards: PluginCard[] = [];
let position = 1;

for (const plugin of plugins) {
	const own = ownSections[plugin.slug];
	if (own !== undefined) {
		cards.push({
			slug: plugin.slug,
			name: plugin.name,
			version: plugin.version,
			summary: own.summary,
			docsPath: own.docsPath,
			storeUrl: storeUrl(plugin.assetId),
		});
		continue;
	}

	const doc = importedDocs[plugin.slug];
	if (doc === undefined) continue;

	writeFileSync(
		path.join(pluginDocsDir, `${plugin.slug}.md`),
		renderPage({
			slug: plugin.slug,
			name: plugin.name,
			version: plugin.version,
			assetId: plugin.assetId,
			position,
			doc,
		}),
	);
	position += 1;
	cards.push({
		slug: plugin.slug,
		name: plugin.name,
		version: plugin.version,
		summary: doc.summary,
		docsPath: `/plugins/${plugin.slug}`,
		storeUrl: storeUrl(plugin.assetId),
	});
}

writeFileSync(path.join(siteDir, "src/data/plugins.json"), `${JSON.stringify(cards, null, "\t")}\n`);

console.log(`Wrote ${position - 1} plugin pages and ${cards.length} cards.`);
